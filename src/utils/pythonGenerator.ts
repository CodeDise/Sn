export function generatePythonBotCode(state: BotState): string {
  const kbJson = JSON.stringify(state.knowledgeBase, null, 4);
  const sectionsJson = JSON.stringify(state.sections, null, 4);
  const productsJson = JSON.stringify(state.products, null, 4);

  return PYTHON_TEMPLATE.replace('__KB_JSON__', kbJson)
    .replace('__SECTIONS_JSON__', sectionsJson)
    .replace('__PRODUCTS_JSON__', productsJson);
}

